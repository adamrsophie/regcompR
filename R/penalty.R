#' Penalties for regularized and bias reduced estimation
#'
#' Builds a penalty on regression coefficients for the `"ml"` engine. The
#' estimate maximizes `loglik(beta) - P(beta)`.
#'
#' Smooth penalties (work with random effects):
#' * `"ridge"`: `P = lambda / 2 * sum(beta^2)`.
#' * `"firth"` (alias `"jeffreys"`): `P = -1/2 log det I(beta)`, Firth's (1993)
#'   penalized likelihood, equivalent to a Jeffreys invariant prior. For
#'   canonical links of exponential families (logistic, Poisson log linear)
#'   it removes the first order bias of the maximum likelihood estimator and
#'   gives finite estimates under separation. `I(beta)` is the expected
#'   information for families whose `eta` second derivatives do not depend on
#'   the response and the observed information otherwise (documented
#'   approximation).
#' * `"flic"`: Firth estimates with the intercept of each penalized
#'   predictor re estimated by maximum likelihood with the other terms as an
#'   offset, so average predicted probabilities equal observed proportions
#'   (Puhr et al. 2017).
#' * `"flac"`: Firth's logistic regression with added covariate: maximum
#'   likelihood on data augmented by pseudo observations weighted by half the
#'   Firth hat values (Puhr et al. 2017). Binary and binomial families only.
#' * `"log_f"`: log F(m, m) prior penalty `P = -sum(m/2 beta - m log(1 + exp(beta)))`
#'   (Greenland and Mansournia 2015).
#' * `"cauchy"`: independent Cauchy priors with scale `scale`,
#'   `P = sum log(1 + (beta / scale)^2)` (Gelman et al. 2008).
#'
#' Non smooth penalties (fitted by accelerated proximal gradient descent,
#' FISTA, for models without random effects):
#' * `"lasso"`: `lambda * sum(|beta|)`.
#' * `"elastic_net"`: `lambda * (alpha * sum(|beta|) + (1 - alpha) / 2 * sum(beta^2))`.
#' * `"adaptive_lasso"`: `lambda * sum(w_j |beta_j|)`, `w_j = 1 / |b_j|^gamma`
#'   from an initial maximum likelihood (or ridge) fit, or user `weights`.
#' * `"group_lasso"`: `lambda * sum_g sqrt(p_g) ||beta_g||_2` for `groups`
#'   (a vector naming the group of each penalized coefficient; by default
#'   the columns generated by one model term form a group).
#' * `"scad"` and `"mcp"`: folded concave penalties (Fan and Li 2001;
#'   Zhang 2010) fitted by the local linear approximation (Zou and Li 2008),
#'   a few reweighted lasso steps started from the lasso.
#'
#' `lambda` is on the scale of the summed log likelihood: `lambda = n *
#' lambda_glmnet` reproduces glmnet and ncvreg, whose losses are averaged
#' over observations. The SCAD and MCP thresholds act on `lambda / n`.
#'
#' Intercepts are never penalized except by `"firth"`, which acts on the
#' whole information matrix. Penalized estimates are not maximum likelihood
#' estimates. For `"firth"`, `"log_f"` and `"cauchy"` the inverse penalized
#' Hessian is reported as the covariance and is the usual large sample
#' approximation; for the others it is not a valid frequentist covariance
#' and p values are suppressed. Choose `lambda` by cross validation.
#'
#' @param type Penalty type, see Details.
#' @param lambda Non-negative penalty weight.
#' @param alpha Elastic net mixing weight in `[0, 1]`.
#' @param pars Parameters whose coefficients are penalized (default all).
#' @param standardize Scale each penalized column by its standard deviation
#'   before penalizing (shrinkage penalties only).
#' @param gamma Adaptive lasso exponent, or the concavity of `"scad"`
#'   (default 3.7) and `"mcp"` (default 3).
#' @param weights Optional adaptive lasso weights.
#' @param groups Optional group labels for `"group_lasso"`.
#' @param m Degrees of freedom of the log F prior.
#' @param scale Scale of the Cauchy prior.
#' @return An object of class `regcomp_penalty`.
#' @references
#' Firth (1993), Bias reduction of maximum likelihood estimates. Biometrika, 80, 27-38.
#' Heinze and Schemper (2002), A solution to the problem of separation in logistic regression. Statistics in Medicine, 21, 2409-2419.
#' Puhr, Heinze, Nold, Lusa and Geroldinger (2017), Firth's logistic regression with rare events. Statistics in Medicine, 36, 2302-2317.
#' Greenland and Mansournia (2015), Penalization, bias reduction, and default priors in logistic and related categorical and survival regressions. Statistics in Medicine, 34, 3133-3143.
#' Gelman, Jakulin, Pittau and Su (2008), A weakly informative default prior distribution for logistic and other regression models. Annals of Applied Statistics, 2, 1360-1383.
#' Tibshirani (1996); Zou and Hastie (2005); Zou (2006); Yuan and Lin (2006); Fan and Li (2001); Zhang (2010); Zou and Li (2008).
#' @export
#' @examples
#' # Complete separation: maximum likelihood diverges, Firth stays finite.
#' d <- data.frame(x = c(-2, -1, -0.5, 0.5, 1, 2), y = c(0, 0, 0, 1, 1, 1))
#' fit <- regcomp(y ~ x, family = "bernoulli", data = d, penalty = penalty("firth"))
#' coef(fit)
#' set.seed(2)
#' X <- matrix(rnorm(200 * 8), 200)
#' d2 <- data.frame(X, y = rpois(200, exp(0.5 + X[, 1] - 0.5 * X[, 2])))
#' fit2 <- regcomp(y ~ ., family = "poisson", data = d2,
#'                 penalty = penalty("lasso", lambda = 5))
#' round(coef(fit2), 3)
penalty <- function(type = c("ridge", "lasso", "elastic_net", "adaptive_lasso", "group_lasso",
                             "scad", "mcp", "firth", "jeffreys", "flic", "flac", "log_f", "cauchy"),
                    lambda = 1, alpha = NULL, pars = NULL, standardize = TRUE,
                    gamma = NULL, weights = NULL, groups = NULL, m = 1, scale = 2.5) {
  type <- match.arg(type)
  if (type == "jeffreys") type <- "firth"
  if (!is.numeric(lambda) || length(lambda) != 1 || lambda < 0)
    stop_input("lambda must be a single non-negative number.")
  if (is.null(alpha)) alpha <- switch(type, elastic_net = 0.5, ridge = 0, 1)
  if (type == "ridge") alpha <- 0
  if (type %in% c("lasso", "adaptive_lasso")) alpha <- 1
  if (alpha < 0 || alpha > 1) stop_input("alpha must lie in [0, 1].")
  if (is.null(gamma)) gamma <- switch(type, scad = 3.7, mcp = 3, 1)
  if (type == "scad" && gamma <= 2) stop_input("SCAD needs gamma > 2.")
  if (type == "mcp" && gamma <= 1) stop_input("MCP needs gamma > 1.")
  if (m <= 0 || scale <= 0) stop_input("m and scale must be positive.")
  structure(list(type = type, lambda = lambda, alpha = alpha, pars = pars,
                 standardize = standardize, gamma = gamma, weights = weights,
                 groups = groups, m = m, scale = scale), class = "regcomp_penalty")
}

#' @export
print.regcomp_penalty <- function(x, ...) {
  extra <- switch(x$type,
    elastic_net = sprintf(", lambda = %g, alpha = %g", x$lambda, x$alpha),
    ridge = , lasso = , adaptive_lasso = , group_lasso = sprintf(", lambda = %g", x$lambda),
    scad = , mcp = sprintf(", lambda = %g, gamma = %g", x$lambda, x$gamma),
    log_f = sprintf(", m = %g", x$m), cauchy = sprintf(", scale = %g", x$scale), "")
  cat(sprintf("<regcomp_penalty> %s%s\n", x$type, extra))
  invisible(x)
}

pen_smooth <- c("ridge", "firth", "flic", "log_f", "cauchy")
pen_valid_cov <- c("firth", "flic", "log_f", "cauchy", "flac")

# Information matrix of the regression coefficients from per observation
# second eta derivatives (expected for response free curvature, observed
# otherwise).
info_matrix <- function(spec, beta) {
  eta <- compute_eta(spec, beta)
  d <- eta_derivs(spec, eta, second = TRUE)
  p <- length(beta); I <- matrix(0, p, p)
  K <- length(spec$rpars)
  for (a in seq_len(K)) for (b in seq_len(K)) {
    ka <- spec$rpars[a]; kb <- spec$rpars[b]
    w <- -spec$weights * d$W[, a, b]
    I[spec$beta_idx[[ka]], spec$beta_idx[[kb]]] <-
      crossprod(spec$preds[[ka]]$X, w * spec$preds[[kb]]$X)
  }
  (I + t(I)) / 2
}

safe_logdet <- function(A) {
  ev <- eigen(A, symmetric = TRUE, only.values = TRUE)$values
  if (any(ev <= 0)) return(-1e10)
  sum(log(ev))
}

num_grad <- function(f, x) {
  vapply(seq_along(x), function(j) {
    h <- 1e-5 * max(1, abs(x[j])); xp <- x; xm <- x
    xp[j] <- xp[j] + h; xm[j] <- xm[j] - h
    (f(xp) - f(xm)) / (2 * h)
  }, 0)
}

make_penalty <- function(pen, spec) {
  if (is.null(pen)) return(NULL)
  if (!inherits(pen, "regcomp_penalty")) stop_input("penalty must come from penalty().")
  # A zero weight is the unpenalized fit.
  if (isTRUE(pen$lambda == 0) && pen$type %in% c("ridge", "lasso", "elastic_net", "adaptive_lasso", "group_lasso", "scad", "mcp"))
    return(NULL)
  pars <- if (is.null(pen$pars)) spec$rpars else pen$pars
  idx <- integer(); scale <- numeric(); grp <- character()
  for (k in intersect(pars, spec$rpars)) {
    X <- spec$preds[[k]]$X
    cols <- which(colnames(X) != "(Intercept)")
    idx <- c(idx, spec$beta_idx[[k]][cols])
    s <- if (pen$standardize && pen$type %in% c("ridge", "lasso", "elastic_net", "adaptive_lasso",
                                                  "group_lasso", "scad", "mcp"))
      apply(X[, cols, drop = FALSE], 2, stats::sd) else rep(1, length(cols))
    s[!is.finite(s) | s == 0] <- 1
    scale <- c(scale, s)
    asg <- attr(X, "assign")
    grp <- c(grp, if (!is.null(asg)) paste(k, asg[cols]) else paste(k, colnames(X)[cols]))
  }
  if (!is.null(pen$groups)) {
    if (length(pen$groups) != length(idx)) stop_input(sprintf("groups must have %d entries, one per penalized coefficient.", length(idx)))
    grp <- as.character(pen$groups)
  }
  pen$prior_scale <- pen$scale
  pen$idx <- idx; pen$scale <- scale; pen$group <- grp
  pen$w <- rep(1, length(idx))
  lam <- pen$lambda; al <- pen$alpha
  pen$smooth <- pen$type %in% pen_smooth
  pen$value <- switch(pen$type,
    firth = , flic = function(beta) -0.5 * safe_logdet(info_matrix(spec, beta)),
    log_f = function(beta) { b <- beta[idx]; -sum(pen$m / 2 * b - pen$m * log1pexp(b)) },
    cauchy = function(beta) sum(log1p((beta[idx] / pen$prior_scale)^2)),
    group_lasso = function(beta) { b <- beta[idx] * scale
      lam * sum(vapply(split(b, grp), function(z) sqrt(length(z)) * sqrt(sum(z^2)), 0)) },
    function(beta) { b <- beta[idx] * scale
      lam * (al * sum(pen$w * abs(b)) + (1 - al) / 2 * sum(b^2)) })
  pen$grad <- switch(pen$type,
    firth = , flic = function(beta) num_grad(pen$value, beta),
    log_f = function(beta) { g <- numeric(length(beta)); b <- beta[idx]
      g[idx] <- -(pen$m / 2 - pen$m * stats::plogis(b)); g },
    cauchy = function(beta) { g <- numeric(length(beta)); b <- beta[idx]
      g[idx] <- 2 * b / (pen$prior_scale^2 + b^2); g },
    function(beta) { g <- numeric(length(beta))
      g[idx] <- lam * (1 - al) * beta[idx] * scale^2; g })
  pen
}

# FISTA for lasso type penalties without random effects. The proximal step
# handles weighted lasso, elastic net and group lasso.
fista <- function(spec, beta0, pen, maxit = 5000, tol = 1e-8) {
  idx <- pen$idx; sc <- pen$scale; lam <- pen$lambda; al <- pen$alpha
  # Work in standardized coordinates c = beta * scale, where the penalty is
  # an ordinary (group) lasso with an exact proximal step.
  unsc <- function(c) { c[idx] <- c[idx] / sc; c }
  ridge_part <- function(c) lam * (1 - al) / 2 * sum(c[idx]^2)
  f <- function(c) -ml_objective(spec, unsc(c)) + ridge_part(c)
  g <- function(c) { gg <- -ml_gradient(spec, unsc(c)); gg[idx] <- gg[idx] / sc + lam * (1 - al) * c[idx]; gg }
  nonsmooth <- function(c) {
    if (pen$type == "group_lasso")
      return(lam * sum(vapply(split(c[idx], pen$group), function(z) sqrt(length(z)) * sqrt(sum(z^2)), 0)))
    lam * al * sum(pen$w * abs(c[idx]))
  }
  prox <- function(c, t) {
    if (pen$type == "group_lasso") {
      for (gname in unique(pen$group)) {
        j <- idx[pen$group == gname]; nv <- sqrt(sum(c[j]^2)); thr <- t * lam * sqrt(length(j))
        c[j] <- if (nv <= thr) 0 else c[j] * (1 - thr / nv)
      }
      return(c)
    }
    v <- c[idx]
    c[idx] <- sign(v) * pmax(abs(v) - t * lam * al * pen$w, 0)
    c
  }
  beta0[idx] <- beta0[idx] * sc
  x <- beta0; yv <- x; tk <- 1; L <- 1
  fx <- f(x); conv <- 1L
  for (it in seq_len(maxit)) {
    gy <- g(yv); fy <- f(yv)
    repeat {
      xn <- prox(yv - gy / L, 1 / L)
      fn <- f(xn)
      if (is.finite(fn) && fn <= fy + sum(gy * (xn - yv)) + L / 2 * sum((xn - yv)^2) + 1e-12) break
      L <- L * 2
      if (L > 1e14) break
    }
    tn <- (1 + sqrt(1 + 4 * tk^2)) / 2
    yv <- xn + (tk - 1) / tn * (xn - x)
    if (fn + nonsmooth(xn) > fx + nonsmooth(x)) { yv <- xn; tk <- 1 } else tk <- tn
    done <- max(abs(xn - x)) < tol * (1 + max(abs(x)))
    x <- xn; fx <- fn
    if (done) { conv <- 0L; break }
  }
  # Stationarity of the nonsmooth problem: the proximal gradient mapping
  # L (x - prox(x - g(x) / L)) is zero exactly at a minimizer.
  kkt <- max(abs(L * (x - prox(x - g(x) / L, 1 / L))))
  list(par = unsc(x), convergence = conv, iterations = it, objective = fx + nonsmooth(x), kkt = kkt)
}

# Derivative of the SCAD and MCP penalties, used as LLA weights.
concave_deriv <- function(type, b, lam, a) {
  b <- abs(b)
  if (type == "scad") ifelse(b <= lam, lam, pmax(a * lam - b, 0) / (a - 1))
  else pmax(lam - b / a, 0)
}

fit_proximal <- function(spec, beta0, pen, control) {
  if (pen$type == "adaptive_lasso") {
    w <- pen$weights
    if (is.null(w)) {
      init <- tryCatch(robust_nlminb(beta0, function(b) { v <- ml_objective(spec, b); if (is.finite(v)) -v else 1e300 },
                                     function(b) -ml_gradient(spec, b), control)$par, error = function(e) beta0)
      w <- 1 / pmax(abs(init[pen$idx] * pen$scale), 1e-8)^pen$gamma
    }
    pen$w <- rep_len(w, length(pen$idx))
  }
  if (pen$type %in% c("scad", "mcp")) {
    lasso <- pen; lasso$type <- "lasso"
    o <- fista(spec, beta0, lasso, control$prox_maxit, control$prox_tol)
    for (step in 1:5) {
      lam0 <- pen$lambda / spec$n
      dw <- concave_deriv(pen$type, o$par[pen$idx] * pen$scale, lam0, pen$gamma) / lam0
      pen$w <- dw
      o <- fista(spec, o$par, pen, control$prox_maxit, control$prox_tol)
    }
    a <- pen$gamma; lam <- pen$lambda / spec$n; nn <- spec$n
    pen$value <- function(beta) { b <- abs(beta[pen$idx] * pen$scale)
      nn * sum(if (pen$type == "scad") ifelse(b <= lam, lam * b, ifelse(b <= a * lam,
        (2 * a * lam * b - b^2 - lam^2) / (2 * (a - 1)), lam^2 * (a + 1) / 2))
        else ifelse(b <= a * lam, lam * b - b^2 / (2 * a), a * lam^2 / 2)) }
  } else o <- fista(spec, beta0, pen, control$prox_maxit, control$prox_tol)
  opt <- list(convergence = o$convergence, message = if (o$convergence == 0) "converged" else "iteration limit",
              iterations = o$iterations, objective = o$objective, kkt = o$kkt,
              controls = list(prox_maxit = control$prox_maxit, prox_tol = control$prox_tol))
  new_fit(spec, o$par, numeric(0), numeric(0), NULL, ml_objective(spec, o$par), opt, "none", pen)
}

# FLIC: refit the intercepts by maximum likelihood with the Firth linear
# predictor (without intercept) as an offset.
flic_adjust <- function(spec, beta, control) {
  ints <- unlist(lapply(spec$rpars, function(k) {
    X <- spec$preds[[k]]$X
    spec$beta_idx[[k]][colnames(X) == "(Intercept)"]
  }))
  if (!length(ints)) return(beta)
  obj <- function(b0) { b <- beta; b[ints] <- b0; v <- ml_objective(spec, b); if (is.finite(v)) -v else 1e300 }
  gr <- function(b0) { b <- beta; b[ints] <- b0; -ml_gradient(spec, b)[ints] }
  o <- robust_nlminb(beta[ints], obj, gr, control)
  beta[ints] <- o$par
  beta
}

# FLAC: Firth fit, then maximum likelihood on augmented data. Each
# observation is duplicated twice with responses y and size - y (binary:
# y and 1 - y), weights h_i / (2 m_i) and an indicator covariate. A row of
# m_i identical trials is m_i Bernoulli rows of leverage h_i / m_i each, whose
# pseudo observations add up to one success and one failure of weight
# h_i / 2; the pair (y, m - y) carries m_i trials, hence the division, so
# grouped and expanded data give the same fit. Rows with no trials add no
# pseudo observations.
flac_fit <- function(spec, control) {
  fam_ok <- spec$fam$id %in% c("bernoulli", "binomial")
  if (!fam_ok) stop_unsupported("FLAC for families other than bernoulli and binomial", spec$fam$id)
  firth <- make_penalty(penalty("firth"), spec)
  b0 <- start_values(spec, control)
  o <- robust_nlminb(b0, function(b) { v <- ml_objective(spec, b) - firth$value(b); if (is.finite(v)) -v else 1e300 },
                     NULL, control)
  I <- info_matrix(spec, o$par)
  k <- spec$rpars[1]; X <- spec$preds[[k]]$X
  eta <- compute_eta(spec, o$par)
  d <- eta_derivs(spec, eta, second = TRUE)
  w <- -spec$weights * d$W[, 1, 1]
  Ii <- safe_inverse(I)
  h <- rowSums((X %*% Ii) * X) * w
  size <- if (spec$fam$id == "binomial") spec$data_pars$size else rep(1, spec$n)
  aug <- spec
  aug$n <- 3 * spec$n
  aug$y <- c(spec$y, spec$y, size - spec$y)
  hw <- ifelse(size > 0, h / (2 * pmax(size, 1)), 0)
  aug$weights <- c(spec$weights, hw, hw)
  aug$cmat <- if (!is.null(spec$cmat)) rbind(spec$cmat, spec$cmat, spec$cmat) else NULL
  Xa <- cbind(rbind(X, X, X), .flac_g = rep(c(0, 1, 1), each = spec$n))
  attr(Xa, "assign") <- c(attr(X, "assign"), max(c(0, attr(X, "assign"))) + 1)
  aug$preds[[k]]$X <- Xa
  aug$preds[[k]]$offset <- rep(spec$preds[[k]]$offset, 3)
  aug$beta_idx[[k]] <- seq_len(ncol(Xa))
  aug$beta_names <- c(spec$beta_names, paste0(k, ":.flac_g"))
  if (!is.null(spec$data_pars)) aug$data_pars <- lapply(spec$data_pars, function(v) rep(v, length.out = 3 * spec$n))
  oa <- robust_nlminb(c(o$par, 0), function(b) { v <- ml_objective(aug, b); if (is.finite(v)) -v else 1e300 },
                      function(b) -ml_gradient(aug, b), control)
  beta <- oa$par[seq_len(ncol(X))]
  cov <- if (control$hessian) safe_inverse(info_matrix(aug, oa$par))[seq_len(ncol(X)), seq_len(ncol(X)), drop = FALSE] else NULL
  list(beta = beta, cov = cov, opt = oa)
}
