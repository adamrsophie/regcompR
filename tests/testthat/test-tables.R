test_that("tidy, glance and augment follow the broom conventions", {
  set.seed(2); d <- data.frame(x = rnorm(300), g = factor(rep(1:30, each = 10)))
  u <- MASS::mvrnorm(30, c(0, 0), matrix(c(.3, .1, .1, .2), 2))
  d$y <- rpois(300, exp(1 + (0.4 + u[d$g, 2]) * d$x + u[d$g, 1]))
  f <- regcomp(y ~ x + (1 + x | g), family = "poisson", data = d)
  t <- tidy.regcomp_fit(f)
  expect_named(t, c("term", "component", "effect", "estimate", "std.error", "statistic", "p.value", "conf.low", "conf.high"))
  vc <- as.data.frame(lme4::VarCorr(lme4::glmer(y ~ x + (1 + x | g), d, poisson)))
  expect_equal(t$estimate[t$term == "sd((Intercept) | g)"], vc$sdcor[1], tolerance = 1e-3)
  expect_equal(t$estimate[t$term == "sd(x | g)"], vc$sdcor[2], tolerance = 1e-3)
  expect_equal(t$estimate[grepl("^cor", t$term)], vc$sdcor[3], tolerance = 1e-3)
  te <- tidy.regcomp_fit(f, exponentiate = TRUE)
  expect_equal(te$estimate[1], exp(t$estimate[1]))
  g <- glance.regcomp_fit(f)
  expect_equal(g$logLik, as.numeric(logLik(f))); expect_equal(g$AIC, AIC(f))
  a <- augment.regcomp_fit(f)
  expect_equal(a$.fitted, unname(fitted(f))); expect_equal(nrow(a), 300)
})

test_that("regression tables print, render and export", {
  set.seed(1); d <- data.frame(x = rnorm(200)); d$y <- rnbinom(200, mu = exp(1 + 0.4 * d$x), size = 2)
  f1 <- regcomp(y ~ x, family = "poisson", data = d); f2 <- regcomp(y ~ x, phi ~ x, family = "nb2", data = d)
  tab <- regcomp_table(P = f1, NB = f2, exponentiate = TRUE, stars = TRUE)
  expect_s3_class(tab, "regcomp_table")
  expect_identical(names(tab), c("parameter", "term", "P", "NB"))
  expect_identical(sub("\\*.*$", "", tab$P[2]), formatC(exp(unname(coef(glm(y ~ x, poisson, d))[2])), digits = 3, format = "f"))
  expect_output(print(tab), "confidence intervals")
  expect_match(as.character(knitr::knit_print(tab)), "Parameter")
  for (e in c("csv", "html", "tex", "md")) {
    fn <- tempfile(fileext = paste0(".", e)); export_table(list(f1, f2), fn)
    expect_gt(file.size(fn), 100)
  }
  expect_error(export_table(tab, tempfile(fileext = ".xyz")), "Unknown table format")
  fn <- tempfile(fileext = ".png"); export_plot(f2, fn, which = "qq"); expect_gt(file.size(fn), 1000)
})
