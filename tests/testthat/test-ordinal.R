test_that("ordinal regression matches MASS::polr and ordinal::clm", {
  skip_if_not_installed("MASS")
  set.seed(1); n <- 500; x <- rnorm(n); z <- rnorm(n)
  y <- cut(.8 * x + rlogis(n) * exp(.3 * z), c(-Inf, -1, .3, 1.5, Inf), labels = letters[1:4], ordered_result = TRUE)
  d <- data.frame(y, x, z)
  f <- regcomp(y ~ x, family = "cumulative_logit", data = d)
  m <- MASS::polr(y ~ x, d, Hess = TRUE)
  expect_equal(f$logLik, as.numeric(logLik(m)), tolerance = 1e-6)
  expect_equal(unname(f$coefficients), unname(c(coef(m), m$zeta)), tolerance = 1e-4)
  expect_equal(unname(sqrt(diag(f$vcov))), unname(sqrt(diag(vcov(m)))), tolerance = 1e-3)
  p <- predict(f, type = "probability")
  expect_equal(unname(rowSums(p)), rep(1, n), tolerance = 1e-10)
  skip_if_not_installed("ordinal")
  f <- regcomp(y ~ x, scale ~ z, family = "cumulative_logit", data = d)
  expect_equal(f$logLik, as.numeric(logLik(ordinal::clm(y ~ x, scale = ~ z, data = d))), tolerance = 1e-6)
})

test_that("multinomial logit matches nnet::multinom", {
  skip_if_not_installed("nnet")
  set.seed(2); n <- 400; x <- rnorm(n)
  d <- data.frame(x, y = factor(sample(c("p", "q", "r"), n, TRUE)))
  f <- regcomp(y ~ x, family = "multinomial_logit", data = d)
  m <- nnet::multinom(y ~ x, d, trace = FALSE)
  expect_equal(f$logLik, as.numeric(logLik(m)), tolerance = 1e-6)
  expect_equal(unname(f$coefficients), as.vector(t(coef(m))), tolerance = 1e-4)
})
