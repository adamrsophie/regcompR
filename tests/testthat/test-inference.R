test_that("anova, wald_test, simple_slopes and vif match glm, the delta method and car", {
  set.seed(1)
  d <- data.frame(x = rnorm(300), z = rnorm(300), f = factor(sample(letters[1:3], 300, TRUE)))
  d$w <- d$x + rnorm(300, 0, 0.3); d$y <- rpois(300, exp(0.5 + 0.3 * d$x + 0.2 * d$x * d$z))
  f1 <- regcomp(y ~ x, family = "poisson", data = d); f2 <- regcomp(y ~ x * z, family = "poisson", data = d)
  g1 <- glm(y ~ x, poisson, d); g2 <- glm(y ~ x * z, poisson, d)
  a <- anova(f1, f2)
  expect_equal(a$Chisq[2], anova(g1, g2)$Deviance[2], tolerance = 1e-5)
  b <- coef(g2); l <- c(0, 1, -1, 0)
  expect_equal(wald_test(f2, c("lambda:x" = 1, "lambda:z" = -1))$chisq, sum(l * b)^2 / drop(t(l) %*% vcov(g2) %*% l), tolerance = 1e-3)
  expect_equal(wald_test(f2, c("lambda:x", "lambda:z"))$df, 2)
  expect_error(wald_test(f2, c("lambda:nope" = 1)), "name coefficients")
  zz <- mean(d$z) + sd(d$z); s <- simple_slopes(f2, "x", "z")
  expect_equal(s$slope[3], unname(b["x"] + b["x:z"] * zz), tolerance = 1e-4)
  expect_equal(s$std_error[3], sqrt(drop(c(1, zz) %*% vcov(g2)[c(2, 4), c(2, 4)] %*% c(1, zz))), tolerance = 1e-3)
  v <- vif(regcomp(y ~ x + w + z + f, family = "poisson", data = d))
  if (requireNamespace("car", quietly = TRUE))
    expect_equal(v$gvif, unname(car::vif(glm(y ~ x + w + z + f, poisson, d))[, 1]), tolerance = 1e-4)
  expect_identical(v$term, c("x", "w", "z", "f"))
})

test_that("johnson_neyman, step_regcomp, plots and standardized tables", {
  set.seed(1); d <- data.frame(x1 = rnorm(300), x2 = rnorm(300), z = rnorm(300))
  d$y <- rpois(300, exp(0.5 + 0.4 * d$x1 + 0.2 * d$x1 * d$z))
  fi <- regcomp(y ~ x1 * z, family = "poisson", data = d)
  b <- coef(fi); V <- vcov(fi)
  s <- function(z) (b[2] + b[4] * z) / sqrt(V[2, 2] + z^2 * V[4, 4] + 2 * z * V[2, 4])
  jn <- johnson_neyman(fi, "x1", "z", n = 401)
  expect_equal(max(jn$bounds), uniroot(function(z) s(z) - qnorm(0.975), c(-2, 0))$root, tolerance = 1e-3)
  fs <- step_regcomp(regcomp(y ~ 1, family = "poisson", data = d), scope = ~ x1 + x2 + z, criterion = "BIC")
  g <- step(glm(y ~ 1, poisson, d), scope = ~ x1 + x2 + z, k = log(300), trace = 0)
  expect_setequal(attr(stats::terms(formula(fs)$lambda), "term.labels"), attr(stats::terms(g), "term.labels"))
  t1 <- tidy.regcomp_fit(fi, standardize = TRUE)
  expect_equal(t1$estimate[t1$term == "x1"], unname(b[2] * sd(d$x1)))
  fn <- tempfile(fileext = ".pdf"); grDevices::pdf(fn)
  expect_silent({ coef_plot(fi, regcomp(y ~ x1 + z, family = "nb2", data = d)); plot(fi, which = "effects", variable = "x1", by = "z")
                  johnson_neyman(fi, "x1", "z", plot = TRUE) })
  grDevices::dev.off()
})
