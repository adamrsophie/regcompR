test_that("iv_regcomp equals AER::ivreg with its diagnostics", {
  skip_if_not_installed("AER")
  set.seed(1)
  n <- 500; z1 <- rnorm(n); z2 <- rnorm(n); w <- rnorm(n); u <- rnorm(n)
  x <- z1 + 0.5 * z2 + 0.3 * w + u + rnorm(n)
  d <- data.frame(y = 1 + 2 * x - w + u, x, z1, z2, w)
  f <- iv_regcomp(y ~ x + w | z1 + z2 + w, data = d)
  s <- summary(AER::ivreg(y ~ x + w | z1 + z2 + w, data = d), diagnostics = TRUE)
  expect_equal(unname(coef(f)), unname(coef(s)[, 1]), tolerance = 1e-8)
  expect_equal(unname(sqrt(diag(vcov(f)))), unname(coef(s)[, 2]), tolerance = 1e-8)
  expect_equal(unname(f$diagnostics$statistic), unname(s$diagnostics[, "statistic"]), tolerance = 1e-8)
  expect_error(iv_regcomp(y ~ x + w | z1, data = d), "not identified")
})

test_that("panel_within and hausman_test equal plm", {
  skip_if_not_installed("plm")
  data("Grunfeld", package = "plm")
  fe <- panel_within(inv ~ value + capital, data = Grunfeld, id = "firm")
  pfe <- plm::plm(inv ~ value + capital, data = Grunfeld, model = "within")
  expect_equal(coef(fe), coef(pfe), tolerance = 1e-8)
  expect_equal(unname(vcov(fe)), unname(vcov(pfe)), tolerance = 1e-8)
  tw <- panel_within(inv ~ value + capital, data = Grunfeld, id = "firm", time = "year", effect = "twoways")
  ptw <- plm::plm(inv ~ value + capital, data = Grunfeld, model = "within", effect = "twoways")
  expect_equal(coef(tw), coef(ptw), tolerance = 1e-8)
  expect_equal(unname(vcov(tw)), unname(vcov(ptw)), tolerance = 1e-8)
  pre <- plm::plm(inv ~ value + capital, data = Grunfeld, model = "random")
  h <- hausman_test(pfe, pre); ph <- plm::phtest(pfe, pre)
  expect_equal(h$statistic, unname(ph$statistic), tolerance = 1e-8)
  G <- Grunfeld; G$firm <- factor(G$firm)
  re <- regcomp(inv ~ value + capital + (1 | firm), family = "normal", data = G)
  expect_equal(hausman_test(fe, re)$df, 2)
})
