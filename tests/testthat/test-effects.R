test_that("avg_effects and marginal_means match the closed forms of a logistic regression", {
  set.seed(1); d <- data.frame(x = rnorm(300), g = factor(sample(c("a", "b", "c"), 300, TRUE)))
  d$y <- rbinom(300, 1, plogis(-0.5 + 0.8 * d$x + (d$g == "b")))
  f <- regcomp(y ~ x + g, family = "bernoulli", data = d); gl <- glm(y ~ x + g, binomial, d)
  e <- avg_effects(f)
  p <- fitted(gl); b <- coef(gl)
  expect_equal(e$estimate[e$term == "x"], mean(b["x"] * p * (1 - p)), tolerance = 1e-5)
  setg <- function(l) predict(gl, transform(d, g = factor(l, levels(d$g))), type = "response")
  expect_equal(e$estimate[e$contrast == "b - a"], mean(setg("b") - setg("a")), tolerance = 1e-5)
  m <- marginal_means(f, "g")
  expect_equal(m$estimate, vapply(levels(d$g), function(l) mean(setg(l)), 0), tolerance = 1e-5, ignore_attr = TRUE)
  expect_true(all(m$std_error > 0))
})

test_that("r2 and icc match MuMIn and performance", {
  skip_if_not_installed("lme4")
  set.seed(2); d <- data.frame(x = rnorm(400), g = factor(rep(1:40, each = 10)))
  d$yn <- 1 + 0.5 * d$x + rnorm(40, 0, 0.7)[d$g] + rnorm(400)
  f <- regcomp(yn ~ x + (1 | g), family = "normal", data = d)
  m <- lme4::lmer(yn ~ x + (1 | g), d, REML = FALSE)
  vc <- as.data.frame(lme4::VarCorr(m))$vcov; vf <- var(drop(model.matrix(m) %*% lme4::fixef(m)))
  expect_equal(unname(r2(f)[c("marginal", "conditional")]), c(vf, vf + vc[1]) / (vf + sum(vc)), tolerance = 1e-4)
  expect_equal(unname(icc(f)["adjusted"]), vc[1] / sum(vc), tolerance = 1e-4)
  fb <- regcomp(yn > 1 ~ x, family = "bernoulli", data = d)
  g0 <- glm(yn > 1 ~ x, binomial, d); g00 <- glm(yn > 1 ~ 1, binomial, d)
  expect_equal(unname(r2(fb)["mcfadden"]), 1 - as.numeric(logLik(g0) / logLik(g00)), tolerance = 1e-6)
  d$yp <- rpois(400, exp(0.5 + 0.4 * d$x + rnorm(40, 0, 0.5)[d$g]))
  fp <- regcomp(yp ~ x + (1 | g), family = "poisson", data = d)
  if (requireNamespace("MuMIn", quietly = TRUE))
    expect_equal(unname(r2(fp)[c("marginal", "conditional")]),
                 unname(suppressWarnings(MuMIn::r.squaredGLMM(lme4::glmer(yp ~ x + (1 | g), d, poisson)))["lognormal", ]), tolerance = 1e-4)
})
